class MonteCarloRunDetailTest {
  // Expected rows come from upstream's runMonteCarloSimulation() with captureRunDetail, picking the
  // run by percentile of the worst-first ranking like the report page does
  @Test
  fun `A median run with income, contributions and a surplus pot matches upstream`() =
    assertCapturedRows(
      meta = INCOME_CONTRIBUTIONS_SURPLUS,
      percentile = 0.5,
      deflate = true,
      expectedIndex = 1446,
      expectedSize = 55,
      expected = MEDIAN_INCOME_ROWS,
    )

  @Test
  fun `A failed run keeps planning unfunded years after depletion`() =
    assertCapturedRows(
      meta = INCOME_CONTRIBUTIONS_SURPLUS,
      percentile = 0.0,
      deflate = true,
      expectedIndex = 79,
      expectedSize = 55,
      expected = FAILED_INCOME_ROWS,
    )

  @Test
  fun `Guardrails explain each year and report locked money on failure`() =
    assertCapturedRows(
      meta = GUARDRAILS_LOCKED_POT,
      percentile = 0.0,
      deflate = true,
      expectedIndex = 3760,
      expectedSize = 40,
      expected = GUARDRAILS_ROWS,
    )

  @Test
  fun `Floor and ceiling anchors in the first spending year`() =
    assertCapturedRows(
      meta = FLOOR_CEILING_FEES,
      percentile = 0.5,
      deflate = true,
      expectedIndex = 3228,
      expectedSize = 30,
      expected = FLOOR_CEILING_ROWS,
    )

  @Test
  fun `Boundaries with tax bands attributes tax to pots`() =
    assertCapturedRows(
      meta = BOUNDARIES_TAX_BANDS,
      percentile = 0.25,
      deflate = true,
      expectedIndex = 2336,
      expectedSize = 40,
      expected = BOUNDARIES_ROWS,
    )

  @Test
  fun `Ratcheting explains its streak`() =
    assertCapturedRows(
      meta = RATCHETING_TARGET_MIX,
      percentile = 1.0,
      deflate = true,
      expectedIndex = 2553,
      expectedSize = 30,
      expected = RATCHETING_ROWS,
    )

  @Test
  fun `Nominal values skip deflation`() =
    assertCapturedRows(
      meta = DEFAULT_PLAN,
      percentile = 0.5,
      deflate = false,
      expectedIndex = 1182,
      expectedSize = 30,
      expected = NOMINAL_ROWS,
    )

  private fun assertCapturedRows(
    meta: String,
    percentile: Double,
    deflate: Boolean,
    expectedIndex: Int,
    expectedSize: Int,
    expected: List<McRunDetailRow>,
  ) {
    val decoded = Json.decodeFromString(ReportMeta.serializer(MonteCarlo), meta)
    val config = assertIs<MonteCarloReportMeta>(decoded).toConfig()
    val result = runMonteCarlo(config, deflate = deflate)
    val ranked = rankSimulationsWorstFirst(result.endingBalances, result.depletionYearBySimulation)
    val index = ranked[(percentile * (result.simulationCount - 1)).roundToLong().toInt()]
    assertThat(index).isEqualTo(expectedIndex)

    val rows = runMonteCarlo(config, deflate = deflate, captureRunDetail = index).runDetail
    assertThat(rows).isNotNull().all {
      prop(List<McRunDetailRow>::size).isEqualTo(expectedSize)
      for (row in expected) {
        transform("year ${row.year}") { it[row.year - 1].normalized() }.isEqualTo(row.normalized())
      }
    }
  }

  // Raw rates can differ from upstream's in the last bit, since JS and the JVM don't share maths
  // functions
  private fun McRunDetailRow.normalized() =
    copy(
      inflation = inflation?.rounded(),
      potReturns = potReturns.map { it?.rounded() }.toImmutableList(),
      ruleExplanation =
        when (val explanation = ruleExplanation) {
          is Anchor -> explanation.copy(rate = explanation.rate.rounded())
          is FloorCeiling -> explanation.copy(rate = explanation.rate.rounded())
          is Factor ->
            explanation.copy(
              factor = explanation.factor.rounded(),
              currentRate = explanation.currentRate?.rounded(),
              referenceRate = explanation.referenceRate?.rounded(),
            )
          null -> null
        },
    )

  private fun Double.rounded() = (this * PRECISION).roundToLong() / PRECISION

  private companion object {
    const val PRECISION = 1e9
  }
}

